"""TypeVector Arena — Common API Schemas, Pagination, and Envelopes."""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class PaginationParams(BaseModel):
    """Standard query parameters for pagination."""

    limit: int = Field(default=20, ge=1, le=100, description="Items to return per page.")
    offset: int = Field(default=0, ge=0, description="Items to skip.")


class PaginatedResponse[T](BaseModel):
    """Standard generic wrapper for paginated collections."""

    items: list[T] = Field(description="Collection of items for current page.")
    total: int = Field(ge=0, description="Total count of available matching items.")
    limit: int = Field(ge=1, description="Page limit used.")
    offset: int = Field(ge=0, description="Page offset used.")
    has_more: bool = Field(description="Whether additional items exist beyond this page.")

    model_config = ConfigDict(from_attributes=True)


class ProblemDetails(BaseModel):
    """RFC 7807 Problem Details representation for OpenAPI schemas."""

    type: str = Field(description="URI reference that identifies the problem type.")
    title: str = Field(description="Short human-readable summary of problem.")
    status: int = Field(description="HTTP status code generated by origin server.")
    detail: str = Field(description="Human-readable explanation specific to occurrence.")
    instance: str = Field(description="URI reference that identifies specific occurrence.")
    code: str = Field(description="Machine-readable error code string.")
    request_id: str = Field(description="Correlated server request identifier.")
    errors: list[dict[str, Any]] | None = Field(
        default=None, description="Optional field-level error details."
    )


class MessageResponse(BaseModel):
    """Standard single-message response envelope."""

    message: str = Field(description="Informative human-readable message.")
